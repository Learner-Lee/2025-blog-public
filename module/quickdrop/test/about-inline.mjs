import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const { chromium } = await import('playwright').catch(() => import('/tmp/quickdrop-test-tools/node_modules/playwright/index.mjs'));
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 1000 } });
await context.route(/fonts\.googleapis\.cn|static\.cloudflareinsights\.com/, route => route.abort());
const page = await context.newPage(), errors = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
const mark = name => { checks.push(name); console.log('PASS', name); };
let release;
try {
  await page.goto('https://web.alenli.cn/about', { waitUntil: 'domcontentloaded', timeout: 90000 });
  const cards = page.locator('[data-work-card]');
  const quick = page.locator('[data-work-card="quickdrop"]');
  await quick.waitFor(); assert.equal(await cards.count(), 2);
  await page.waitForFunction(() => [...document.querySelectorAll('[data-work-card]')].every(node => Number(getComputedStyle(node).opacity) === 1));
  const first = await cards.first().boundingBox(), second = await cards.nth(1).boundingBox();
  assert.ok(Math.abs(first.y - second.y) < 2 && second.x > first.x + first.width);
  await quick.hover(); await page.waitForFunction(() => new DOMMatrix(getComputedStyle(document.querySelector('[data-work-card="quickdrop"]')).transform).a > 1.02);
  await page.mouse.move(10, 10); mark('Two-column cards retain hover enlargement');
  assert.equal(await page.getByRole('link', { name: '在线体验 ↗', exact: true }).count(), 2);
  const popupPromise = page.waitForEvent('popup'); await quick.getByRole('link', { name: '在线体验 ↗', exact: true }).click();
  const popup = await popupPromise; await popup.waitForLoadState('domcontentloaded', { timeout: 60000 });
  assert.equal(new URL(popup.url()).pathname, '/quickdrop/'); await popup.close();
  assert.equal(await cards.count(), 2); assert.equal(new URL(page.url()).pathname, '/about');
  mark('Compact cards expose experience links without expanding');
  await page.evaluate(() => { window.__galleryDocument = 'same-document'; });
  let blocked = true, held = 0;
  const gate = new Promise(resolve => { release = resolve; });
  await page.route('**/_next/static/chunks/**', async route => {
    if (blocked && route.request().resourceType() === 'script') { held++; await gate; }
    await route.continue().catch(() => {});
  });
  await page.getByRole('button', { name: '展开「QuickDrop · 网页互传」详情', exact: true }).click();
  const bar = page.getByRole('progressbar', { name: '内容加载进度' });
  await bar.waitFor({ timeout: 15000 });
  await page.waitForFunction(() => document.querySelector('[role="progressbar"]')?.getAttribute('aria-valuenow') === '99', null, { timeout: 15000 });
  assert.ok(held > 0, 'network delay actually blocked a detail script');
  assert.equal(await cards.count(), 1); assert.equal(await quick.getAttribute('data-expanded'), 'true');
  assert.ok((await quick.boundingBox()).width > second.width * 1.8);
  assert.equal(new URL(page.url()).pathname, '/about');
  assert.equal(await page.evaluate(() => window.__galleryDocument), 'same-document');
  assert.equal(await page.getByTestId('work-description').isVisible(), false);
  const cat = page.locator('[data-testid="cat-loader"] svg');
  assert.notEqual(await cat.evaluate(node => getComputedStyle(node).animationName), 'none');
  await page.screenshot({ path: new URL('../test-results/about-cat-99.png', import.meta.url).pathname });
  await page.waitForTimeout(1000); assert.equal(await bar.getAttribute('aria-valuenow'), '99');
  mark('Expansion stays on the same page; jumping cat waits at 99% under delayed loading');
  blocked = false; release();
  await page.getByTestId('work-description').waitFor({ state: 'visible', timeout: 90000 });
  await page.getByTestId('cat-loader').waitFor({ state: 'hidden', timeout: 15000 });
  assert.match(await page.getByTestId('work-description').innerText(), /可以做什么/);
  assert.equal(await page.evaluate(() => window.__galleryDocument), 'same-document');
  await page.screenshot({ path: new URL('../test-results/about-inline-expanded.png', import.meta.url).pathname, fullPage: true });
  mark('Actual ready content completes the loader and appears inline');
  await page.getByRole('button', { name: '收起「QuickDrop · 网页互传」详情', exact: true }).click();
  await cards.nth(1).waitFor(); assert.equal(await cards.count(), 2);
  await page.getByRole('button', { name: '展开「PDF 对照」详情', exact: true }).click();
  await page.getByTestId('work-description').waitFor({ state: 'visible', timeout: 90000 });
  await page.keyboard.press('Escape'); await cards.nth(1).waitFor();
  assert.equal(await page.getByTestId('cat-loader').count(), 0);
  mark('Both works expand and collapse; Escape restores the gallery');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
  const left = await cards.first().boundingBox(), right = await cards.nth(1).boundingBox();
  assert.ok(Math.abs(left.x - right.x) < 2 && right.y > left.y + left.height);
  await quick.getByRole('link', { name: '在线体验 ↗', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: new URL('../test-results/about-inline-mobile.png', import.meta.url).pathname });
  await page.setViewportSize({ width: 1280, height: 1000 });
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  await page.getByPlaceholder('作品名称').first().waitFor(); assert.equal(await page.getByPlaceholder('作品名称').count(), 2);
  await page.getByRole('button', { name: '取消', exact: true }).click();
  mark('Mobile experience buttons and existing editor remain usable');
  await page.goto('https://web.alenli.cn/about/quickdrop', { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.waitForURL('**/about?work=quickdrop', { waitUntil: 'domcontentloaded' });
  await page.getByTestId('work-description').waitFor({ state: 'visible', timeout: 90000 });
  assert.equal(await page.locator('[data-work-card]').count(), 1);
  await page.getByRole('button', { name: '收起「QuickDrop · 网页互传」详情', exact: true }).click();
  assert.equal(new URL(page.url()).search, '');
  mark('Previous detail bookmarks open the inline gallery view');
  assert.deepEqual(errors, []);
  await writeFile(new URL('../test-results/about-inline-report.json', import.meta.url), JSON.stringify({ ok: true, checks, errors }, null, 2));
} catch (error) {
  console.log(error.stack, 'BODY', await page.locator('body').innerText().catch(() => 'unavailable'), 'ERRORS', errors);
  await page.screenshot({ path: new URL('../test-results/about-inline-failure.png', import.meta.url).pathname }).catch(() => {});
  await writeFile(new URL('../test-results/about-inline-report.json', import.meta.url), JSON.stringify({ ok: false, checks, error: error.stack, errors }, null, 2));
  process.exitCode = 1;
} finally { release?.(); await browser.close(); }
